export const DEFAULT_UNIT = '3bhk';

/** Read ?unit= from the QR-code URL, falling back to the 3 BHK. */
export function currentUnitKey() {
  const raw = new URLSearchParams(location.search).get('unit');
  const key = (raw || '').toLowerCase().replace(/[^a-z0-9]/g, '');
  return UNITS[key] ? key : DEFAULT_UNIT;
}

export function currentUnit() {
  return UNITS[currentUnitKey()];
}
